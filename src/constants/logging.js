// ============================================================================
// logging.js —— 日志系统的常量单一来源
//
// 背景：本轮之前项目里没有日志，诊断信息散在约 41 处裸 `console.*`，主进程与渲染
// 进程各写各的，一次跨 IPC 的失败没法在同一份记录里串起来（R-L3）。统一内核的
// 第一步就是把「级别怎么排 / 缓冲多大 / 轮转阈值 / 存在哪个 localStorage key」
// 这些约定从代码里抽出来，让 logger（src/utils/logger.js）、主进程落盘（T09）与
// 设置页（R-L5）读的是同一份数字，而不是各抄一遍再慢慢漂移。
//
// 硬约束：**本文件必须零 import、零副作用**。
// 与 utils/fileNaming.js 同一个理由 —— 它要同时被
//   · 渲染进程（ESM，走 Vite 打包）
//   · 主进程（electron/main.cjs，CommonJS）
//   · 单测（vitest / 纯 node）
// 复用。任何依赖都会让其中一侧加载不了。这里连 type-only 的工具函数都不放，
// 只放数据；需要计算的地方一律放进 logger.js / logSanitize.js。
//
// 数值口径出处：design §3.4「关键接口签名」与 §4.4「日志格式」，用户已拍板
// 「默认 info、2MB 轮转、保留 7 天、不引入第三方日志库」。
// ============================================================================

// ---------------------------------------------------------------------------
// 级别
// ---------------------------------------------------------------------------

/**
 * 日志级别 → 权重。**数值越大越严重**，比较权重即可决定是否放行。
 *
 * `silent` 是「闸门」而不是「可输出的级别」：它只出现在 CONFIG 里表示全部关掉，
 * 永远不会出现在 LogEntry.lvl 上（否则就好写了永远不成立的分支）。所以下面的
 * LOG_LEVEL_ORDER 刻意不含 silent。
 */
export const LOG_LEVELS = Object.freeze({
  debug: 10,
  info: 20,
  warn: 30,
  error: 40,
  silent: 100
})

/** 可输出级别的先后顺序（不含 silent），供设置页下拉框与合法性校验复用 */
export const LOG_LEVEL_ORDER = Object.freeze(['debug', 'info', 'warn', 'error'])

/** 默认级别：Q8 建议值，用户已拍板采纳。生产环境不该被 debug 刷屏 */
export const DEFAULT_LOG_LEVEL = 'info'

// ---------------------------------------------------------------------------
// 落盘与保留（T09 主进程落盘消费）
// ---------------------------------------------------------------------------

/** 单文件上限，超过就把 main.log 轮转为 main.1.log */
export const LOG_MAX_BYTES = 2 * 1024 * 1024

/** 轮转文件的保留天数，超期的清理掉 */
export const LOG_KEEP_DAYS = 7

/** 轮转文件的最大个数，防止极端情况下无限堆叠 */
export const LOG_MAX_FILES = 7

/** 日志文件所在目录名（挂在 app.getPath('userData') 下） */
export const LOG_DIR_NAME = 'logs'

/** 主日志文件基本名 */
export const LOG_FILE_NAME = 'main.log'

// ---------------------------------------------------------------------------
// 渲染进程内存缓冲
// ---------------------------------------------------------------------------

/**
 * 环形缓冲条数。存在两个地方的意义不同：
 *   · 渲染进程（未落盘 / 浏览器降级）：它是**唯一的留存**，设置页「查看日志」读它；
 *   · Electron 下（T09 接通 IPC 后）：它是「最近 N 条」的快速预览，全量仍在文件里。
 * 500 条约等于一次异常前后的完整上下文，又不会让内存持有一万条 note 内容副本。
 */
export const LOG_RING_SIZE = 500

// ---------------------------------------------------------------------------
// 持久化：级别存哪里
// ---------------------------------------------------------------------------

/**
 * 日志级别的 localStorage key。
 *
 * 注意：本 key 需要同时登记进 `src/constants/storage.js` 的 LS_KEYS（design §4.3），
 * 但 storage.js 不属于本任务（T08）的 owns，为避免并行冲突，**这里只导出常量、
 * 不去改 storage.js**。交接给设置页任务时记得同步补 LS_KEYS 一条 `logLevel`。
 *
 * 由谁来读：不是 logger 自己 —— logger 必须能跑在没有 localStorage 的主进程里，
 * 所以它只提供 `setLogLevel()`；初始化时由渲染侧宿主（App 引导或 T10/T11）读这里
 * 的值喂进来。
 */
export const LS_LOG_LEVEL = 'choyeon-log-level'

// ---------------------------------------------------------------------------
// 文本行格式（design §4.4：主/渲染共用，必须逐字节一致）
// ---------------------------------------------------------------------------

/**
 * 级别栏宽度。格式是 `<时间>  <级别>  [模块]  <消息>  <k=v…>`，级别左对齐补空格到
 * 5 个字符（'INFO ' / 'WARN ' / 'ERROR' / 'DEBUG'），这样消息正文的起始列是固定的，
 * 人眼扫一列时间戳后面的内容不会被长短不一的级别词错位带偏。
 */
export const LOG_LEVEL_WIDTH = 5

/** 字段之间的固定分隔符（两个空格） */
export const LOG_FIELD_SEP = '  '

// ---------------------------------------------------------------------------
// 脱敏
// ---------------------------------------------------------------------------

/**
 * 单条字符串进入日志前的截断上限。
 *
 * 为什么是 120：既要能看出「这条内容片段是什么」（只剩 20 字符时等于没记），又不能
 * 把整篇笔记灌进日志文件 —— 日志是要能被用户直接贴进 GitHub Issue 的（R-L6），
 * 一篇 10KB 的笔记正文进来，一份日志就变成数据本体了。
 *
 * 注意：`src/utils/logSanitize.js` 里 `redactContent(s, max = 120)` 的默认值必须与
 * 此处相等。那份默认值不能 import 这里（logSanitize 要求零 import），属于刻意的、
 * 有注释标注的重复常量，改一处必须改另一处。
 */
export const LOG_CONTENT_MAX = 120

/**
 * `sanitizeValue` 遍历一棵未知对象树时给**单个字符串**的上限。
 *
 * 与 LOG_CONTENT_MAX 的区别：120 用于「明确知道是笔记内容」的片段
 * （design §3.4 规则 3），200 用于「sanitizeValue 在树上偶然遇到的字符串」的兜底，
 * 两者都远低于「一篇笔记」的量级。**logger 实际调用时统一传 LOG_CONTENT_MAX（120）**，
 * 见 logger.js 的 buildSanitizer —— 即通过日志出去的字符串一律 120。
 */
export const LOG_MAX_STRING = 200

/** sanitizeValue 默认下潜层数：够覆盖 `{ err: { cause: {...} } }`，又不会把整棵 Vue 响应式树拖进来 */
export const LOG_MAX_DEPTH = 3

// ---------------------------------------------------------------------------
// 模块名约定（design §4.4）
// ---------------------------------------------------------------------------

/**
 * 模块名取值单一来源。要求 `createLogger(MODULE)` 而不是手写字符串，是为了让
 * 「按模块过滤」（R-L4）真的可用 —— 一旦有人写 `noteStore` 有人写 `note`，
 * 过滤条件就得写成 `mod.startsWith('note')` 这种兜补丁，过滤能力名存实亡。
 */
export const LOG_MODULES = Object.freeze({
  note: 'note',
  app: 'app',
  vault: 'vault',
  workspace: 'workspace',
  watcher: 'watcher',
  ipc: 'ipc',
  graph: 'graph',
  calendar: 'calendar',
  editor: 'editor',
  sync: 'sync',
  // T11 要求的两个额外模块（console 迁移：composables）
  actions: 'actions',
  commands: 'commands',
  // T09 主进程落盘侧
  main: 'main'
})
